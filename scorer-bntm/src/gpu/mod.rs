/// Flat GPU state for `BnTmScorer`. Single-cluster streaming wrapper.
/// The LRU is degenerate (one cluster) but the surface stays uniform
/// with `IvfGpuState` and the NVML peak sampler runs uniformly across
/// variants.
///
/// Host-side M_enc / AL / H stay around so the upload closure can
/// rebuild on (degenerate) LRU eviction and so the NVML sampler can
/// run over the whole handle lifetime. The sparse `S` matrix is held
/// here and shared with the host-side decode orchestrator via
/// [`s_mat_arc`](Self::s_mat_arc).
pub struct FlatGpuState {
    m_enc_host: Vec<u64>,
    a_l_host: Vec<u64>,
    h_host: Vec<u64>,
    m: usize,
    params: BnTmParams,
    store: ClusterStore<ClusterBuf>,
    sampler: Option<PeakVramSampler>,
    /// Pre-derived sparse `S` matrix, shared with the host-side decode
    /// orchestrator. Memory ≈ `m · μn · 5 B` at SEC128 (≈ 18 MiB at
    /// m = 100 000).
    s_mat: Arc<SparseMatrix>,
}

impl FlatGpuState {
    /// Construct the streaming state. The device cluster buffer
    /// isn't built yet — the first `compute_products` (or
    /// `decode_dense_terms`) call triggers the upload via
    /// `ClusterStore::get_or_upload`. Matches the IVF variant's
    /// lazy-upload semantics so the NVML sampler runs from
    /// handle-build through the first kernel launch.
    pub fn build(
        m_enc_host: &[u64],
        a_l_host: &[u64],
        h_host: &[u64],
        s_mat: Arc<SparseMatrix>,
        m: usize,
        params: BnTmParams,
        vram_budget_bytes: Option<u64>,
    ) -> Result<Self, GpuError> {
        let k = kernel()?;
        let upload_stream = k.ctx.new_stream()?;
        let compute_stream = k.ctx.new_stream()?;
        let nvml_idx = nvml_index_for_cuda_device(0);
        let budget = resolve_budget(vram_budget_bytes, nvml_idx)?;
        let store = ClusterStore::<ClusterBuf>::new(
            Arc::clone(&k.ctx),
            budget,
            upload_stream,
            compute_stream,
        );
        let sampler = PeakVramSampler::start_default(nvml_idx).ok();

        Ok(FlatGpuState {
            m_enc_host: m_enc_host.to_vec(),
            a_l_host: a_l_host.to_vec(),
            h_host: h_host.to_vec(),
            m,
            params,
            store,
            sampler,
            s_mat,
        })
    }

    pub fn peak_vram_bytes(&self) -> Option<u64> {
        self.sampler.as_ref().map(|s| s.peak_bytes())
    }

    pub fn vram_budget_bytes(&self) -> u64 {
        self.store.budget_bytes()
    }

    /// `Arc` clone of the cached sparse `S` so the caller can move it
    /// into a `spawn_blocking` closure ahead of the
    /// `decode_scores_with_gpu_dense` call.
    pub fn s_mat_arc(&self) -> Arc<SparseMatrix> {
        Arc::clone(&self.s_mat)
    }

    /// Compute the per-query device payload size hint that the
    /// streaming store uses to pre-evict on alloc-fail. Matches
    /// `ClusterBuf::device_bytes` for the flat handle.
    fn payload_hint(&self) -> u64 {
        (self.m as u64) * (self.params.n() as u64 + 2 * (self.params.n1() as u64)) * 8
    }

    /// Run `compute_products` for one query against the device-
    /// resident cluster (uploaded lazily on first call). `v_enc` is
    /// the host-side encoded query (already padded to n by
    /// `crypto::encode_query`); returns the length-m response vector
    /// r in F_p, identical to the CPU `crypto::compute_products`
    /// output.
    pub fn compute_products(&self, v_enc: &[u64]) -> Result<Vec<u64>, GpuError> {
        debug_assert_eq!(v_enc.len(), self.params.n());
        let k = kernel()?;
        let m = self.m;
        let params = self.params;
        let m_enc_host = &self.m_enc_host;
        let a_l_host = &self.a_l_host;
        let h_host = &self.h_host;
        let cell = self.store.get_or_upload::<_, cudarc::driver::DriverError>(
            0,
            self.payload_hint(),
            |upload_stream| {
                upload_cluster_buffers(upload_stream, m_enc_host, a_l_host, h_host, m, params)
            },
        )?;
        let cluster = cell.lock();
        launch_compute_products(k, &cluster, v_enc)
    }

    /// Compute the dense partial of the decode-side correction:
    /// `AL · g + H · lt_venc` over F_p, returned as a length-`m` host
    /// vector.
    ///
    /// Two H2D copies per query (`g` and `lt_venc`, each length n_1),
    /// two `bntm_decode_dense` launches against the device-resident
    /// `AL` and `H`, one `bntm_add_mod_vec` to combine the outputs,
    /// one D2H. The sparse pieces (`M · T`, `S · v_enc`) stay on
    /// host and are subtracted by `decode_scores_with_gpu_dense`.
    pub fn decode_dense_terms(&self, g: &[u64], lt_venc: &[u64]) -> Result<Vec<u64>, GpuError> {
        debug_assert_eq!(g.len(), self.params.n1());
        debug_assert_eq!(lt_venc.len(), self.params.n1());
        let k = kernel()?;
        let m = self.m;
        let params = self.params;
        let m_enc_host = &self.m_enc_host;
        let a_l_host = &self.a_l_host;
        let h_host = &self.h_host;
        let cell = self.store.get_or_upload::<_, cudarc::driver::DriverError>(
            0,
            self.payload_hint(),
            |upload_stream| {
                upload_cluster_buffers(upload_stream, m_enc_host, a_l_host, h_host, m, params)
            },
        )?;
        let cluster = cell.lock();
        launch_decode_dense_terms(k, &cluster, g, lt_venc)
    }
}

// ---------------------------------------------------------------------------
// IVF variant — streaming. Host-side per-cluster EncryptedCluster
// payloads (mmap-backed `m_enc` / `a_l`) uploaded lazily on miss; H
// regenerated from each cluster's `h_seed` in the upload closure; LRU
// evicts on budget pressure. The sparse `S` matrix per cluster is held
// host-side in `s_mats`, never device-resident.
// ---------------------------------------------------------------------------

/// Streaming GPU state for `BnTmIvfScorer`. Shares the scorer's
/// `Arc<Vec<EncryptedCluster>>` so the upload closure can read each
/// cluster's `m_enc` / `a_l` directly — which is **zero-copy** when
/// the cache file is mmap-backed (the 8.8M build path at scale).
pub struct IvfGpuState {
    clusters: Arc<Vec<crate::EncryptedCluster>>,
    /// Pre-derived sparse `S` matrices, one per cluster (or `None` for
    /// empty clusters). Eagerly generated at `build()` time so the GPU
    /// decode dispatch can compute `S · v_enc` per query on host
    /// without re-running the single-threaded ChaCha20 sample loop.
    /// Host RAM cost ≈
    /// `n_centroids · m_avg · μn · 5 B` (≈ 5 GB at 8.8 M / 317
    /// centroids, well within the sacs006 RAM budget).
    s_mats: Vec<Option<Arc<SparseMatrix>>>,
    params: BnTmParams,
    store: ClusterStore<ClusterBuf>,
    sampler: Option<PeakVramSampler>,
}

impl IvfGpuState {
    /// Build the streaming state from the scorer's per-cluster
    /// encrypted state. We hold an `Arc<Vec<EncryptedCluster>>`
    /// directly so mmap-backed `m_enc` / `a_l` regions stay
    /// page-cache-zero-copy through the streaming upload path.
    pub fn build(
        clusters: Arc<Vec<crate::EncryptedCluster>>,
        params: BnTmParams,
        vram_budget_bytes: Option<u64>,
    ) -> Result<Self, GpuError> {
        let k = kernel()?;
        let upload_stream = k.ctx.new_stream()?;
        let compute_stream = k.ctx.new_stream()?;
        let nvml_idx = nvml_index_for_cuda_device(0);
        let budget = resolve_budget(vram_budget_bytes, nvml_idx)?;
        let store = ClusterStore::<ClusterBuf>::new(
            Arc::clone(&k.ctx),
            budget,
            upload_stream,
            compute_stream,
        );
        let sampler = PeakVramSampler::start_default(nvml_idx).ok();

        // S is already materialised on each `EncryptedCluster` (Plan
        // 28) — just Arc-clone it, no regeneration needed.
        let s_mats: Vec<Option<Arc<SparseMatrix>>> = clusters
            .iter()
            .map(|c| {
                if c.m == 0 {
                    None
                } else {
                    Some(Arc::clone(&c.s_mat))
                }
            })
            .collect();

        Ok(IvfGpuState {
            clusters,
            s_mats,
            params,
            store,
            sampler,
        })
    }

    pub fn peak_vram_bytes(&self) -> Option<u64> {
        self.sampler.as_ref().map(|s| s.peak_bytes())
    }

    pub fn vram_budget_bytes(&self) -> u64 {
        self.store.budget_bytes()
    }

    /// `Arc` clone of one cluster's cached sparse `S`. `None` for
    /// empty / out-of-range clusters; otherwise the caller moves the
    /// Arc into a `spawn_blocking` closure ahead of the
    /// `decode_scores_with_gpu_dense` call.
    pub fn s_mat_arc(&self, ci: usize) -> Option<Arc<SparseMatrix>> {
        self.s_mats.get(ci).and_then(|s| s.clone())
    }

    fn cluster_payload_hint(&self, m: usize) -> u64 {
        (m as u64) * (self.params.n() as u64 + 2 * (self.params.n1() as u64)) * 8
    }

    /// Run `compute_products` for cluster `ci`, uploading on miss +
    /// evicting LRU tail under budget pressure. Returns `None` for
    /// empty / out-of-range clusters so the caller can skip them.
    pub fn compute_products(&self, ci: usize, v_enc: &[u64]) -> Result<Option<Vec<u64>>, GpuError> {
        debug_assert_eq!(v_enc.len(), self.params.n());
        let Some(cluster_meta) = self.clusters.get(ci) else {
            return Ok(None);
        };
        let m = cluster_meta.m;
        if m == 0 {
            return Ok(None);
        }
        let k = kernel()?;
        let params = self.params;
        let clusters = Arc::clone(&self.clusters);
        let cell = self.store.get_or_upload::<_, cudarc::driver::DriverError>(
            ci,
            self.cluster_payload_hint(m),
            move |upload_stream| {
                let c = &clusters[ci];
                upload_cluster_buffers(
                    upload_stream,
                    c.m_enc.as_slice(),
                    c.a_l.as_slice(),
                    c.h_mat.as_slice(),
                    m,
                    params,
                )
            },
        )?;
        let cluster = cell.lock();
        let r = launch_compute_products(k, &cluster, v_enc)?;
        Ok(Some(r))
    }

    /// `AL · g + H · lt_venc` for one cluster. Mirrors
    /// [`FlatGpuState::decode_dense_terms`]; `None` for empty /
    /// out-of-range clusters.
    pub fn decode_dense_terms(
        &self,
        ci: usize,
        g: &[u64],
        lt_venc: &[u64],
    ) -> Result<Option<Vec<u64>>, GpuError> {
        debug_assert_eq!(g.len(), self.params.n1());
        debug_assert_eq!(lt_venc.len(), self.params.n1());
        let Some(cluster_meta) = self.clusters.get(ci) else {
            return Ok(None);
        };
        let m = cluster_meta.m;
        if m == 0 {
            return Ok(None);
        }
        let k = kernel()?;
        let params = self.params;
        let clusters = Arc::clone(&self.clusters);
        let cell = self.store.get_or_upload::<_, cudarc::driver::DriverError>(
            ci,
            self.cluster_payload_hint(m),
            move |upload_stream| {
                let c = &clusters[ci];
                upload_cluster_buffers(
                    upload_stream,
                    c.m_enc.as_slice(),
                    c.a_l.as_slice(),
                    c.h_mat.as_slice(),
                    m,
                    params,
                )
            },
        )?;
        let cluster = cell.lock();
        let r = launch_decode_dense_terms(k, &cluster, g, lt_venc)?;
        Ok(Some(r))
    }
}

// ---------------------------------------------------------------------------
// Kernel launch glue.
// ---------------------------------------------------------------------------

fn launch_compute_products(
    k: &BnTmKernel,
    cluster: &ClusterBuf,
    v_enc: &[u64],
) -> Result<Vec<u64>, GpuError> {
    let m = cluster.m;
    let v_dev = k.stream.clone_htod(v_enc)?;
    let mut r_dev: CudaSlice<u64> = k.stream.alloc_zeros(m)?;

    let m_u32 = u32::try_from(m).expect("cluster size must fit in u32");
    // Warp-per-row layout. One block per output row, 256 threads per
    // block cooperatively reducing the N=1024 dot product. Shared
    // memory holds v_enc (1024 × 8 = 8192 bytes) and 8 cross-warp
    // partials (overlapped into the same 8192-byte declaration on the
    // kernel side; we pass the v_enc cache size here).
    let cfg = LaunchConfig {
        grid_dim: (m_u32, 1, 1),
        block_dim: (BLOCK_DIM, 1, 1),
        shared_mem_bytes: 0,
    };

    let mut launch = k.stream.launch_builder(&k.compute_products);
    launch.arg(&cluster.m_enc_dev);
    launch.arg(&v_dev);
    launch.arg(&mut r_dev);
    launch.arg(&m_u32);
    unsafe { launch.launch(cfg)? };

    let r = k.stream.clone_dtoh(&r_dev)?;
    Ok(r)
}

/// Compose `AL · g + H · lt_venc` on device and return the length-`m`
/// result as a host vector.
///
/// One `bntm_decode_dense` launch per matrix (the kernel reads any
/// `m × n_1` row-major buffer in F_p), then one `bntm_add_mod_vec`
/// over the two length-`m` outputs. `g` and `lt_venc` are uploaded
/// with two separate H2Ds per query.
fn launch_decode_dense_terms(
    k: &BnTmKernel,
    cluster: &ClusterBuf,
    g: &[u64],
    lt_venc: &[u64],
) -> Result<Vec<u64>, GpuError> {
    let m = cluster.m;
    let m_u32 = u32::try_from(m).expect("cluster size must fit in u32");

    let g_dev = k.stream.clone_htod(g)?;
    let lt_venc_dev = k.stream.clone_htod(lt_venc)?;

    let dense_cfg = LaunchConfig {
        grid_dim: (m_u32, 1, 1),
        block_dim: (BLOCK_DIM, 1, 1),
        shared_mem_bytes: 0,
    };

    // r1 = AL · g
    let mut r1_dev: CudaSlice<u64> = k.stream.alloc_zeros(m)?;
    let mut launch = k.stream.launch_builder(&k.decode_dense);
    launch.arg(&cluster.a_l_dev);
    launch.arg(&g_dev);
    launch.arg(&mut r1_dev);
    launch.arg(&m_u32);
    unsafe { launch.launch(dense_cfg)? };

    // r2 = H · lt_venc
    let mut r2_dev: CudaSlice<u64> = k.stream.alloc_zeros(m)?;
    let mut launch = k.stream.launch_builder(&k.decode_dense);
    launch.arg(&cluster.h_dev);
    launch.arg(&lt_venc_dev);
    launch.arg(&mut r2_dev);
    launch.arg(&m_u32);
    unsafe { launch.launch(dense_cfg)? };

    // out = r1 + r2  (mod P)
    let mut out_dev: CudaSlice<u64> = k.stream.alloc_zeros(m)?;
    let add_grid = m_u32.div_ceil(ADD_MOD_BLOCK_DIM);
    let add_cfg = LaunchConfig {
        grid_dim: (add_grid, 1, 1),
        block_dim: (ADD_MOD_BLOCK_DIM, 1, 1),
        shared_mem_bytes: 0,
    };
    let mut launch = k.stream.launch_builder(&k.add_mod_vec);
    launch.arg(&r1_dev);
    launch.arg(&r2_dev);
    launch.arg(&mut out_dev);
    launch.arg(&m_u32);
    unsafe { launch.launch(add_cfg)? };

    let out = k.stream.clone_dtoh(&out_dev)?;
    Ok(out)
}
