//! cudarc-backed GPU paths for `scorer-bntm`, using the streaming
//! cluster store from `scorer-gpu-common`.
//!
//! Compiled only when the `gpu` Cargo feature is enabled. The CUDA
//! kernel source lives in `kernels.cu`; `build.rs` invokes `nvcc` at
//! crate build time to produce `bntm_kernels.ptx` in `OUT_DIR`, which
//! `include_str!` pulls in below. Requires the rapids conda env
//! (provides nvcc 12.4).
//!
//! ## What the GPU path actually does
//!
//! Only the server-side `compute_products` matvec and the
//! `decode_dense_terms` `(AL · g + H · lt_venc)` step move to device.
//! Encryption (`encrypt_cluster`), query encoding (`encode_query`),
//! Protocol 2 verification (`verify_response`), and the host-side
//! composition of the final dense + sparse decode
//! (`decode_scores_with_gpu_dense`) all stay on host.
//!
//! ## Streaming
//!
//! An earlier design held all IVF clusters' device buffers (M_enc, AL,
//! H) device-resident at `upload_cluster` time. Peak VRAM =
//! `n_centroids × m_avg × (n + 2·n_1) × 8` ≈ 50 GB at 8.8 M corpus /
//! 317 centroids on a 32 GB card, which OOMs.
//!
//! Instead, `IvfGpuState` keeps the host-side per-cluster
//! `EncryptedCluster` payload (mmap-backed `m_enc` / `a_l` / `h_mat`)
//! and lazily builds the device-resident `ClusterBuf` on miss. The
//! streaming [`ClusterStore`] holds the device tuple under an LRU
//! bounded by `--gpu-vram-budget-bytes` (default NVML 80 %); on
//! miss-then-evict it drops the LRU tail's `CudaSlice<u64>`s,
//! returning device memory to the cudarc memory pool. A subsequent
//! re-hit re-uploads M_enc + AL + H straight from the host-resident
//! `EncryptedCluster` (materialised once at handle build / cache load;
//! no per-re-hit regeneration).
//!
//! The host-side sparse `S` matrix stays on host in
//! `IvfGpuState::s_mats`; it's never device-resident.
//!
//! Unlike the cuvs scorers (plaintext / sap), BN's cluster device
//! buffers are pure `CudaSlice<u64>` that cudarc owns end-to-end —
//! `Drop` returns memory to the cudarc memory pool cleanly. No
//! manual `cuvsRMMFree` dance, no DLPack deleter suppression. Same
//! streaming shape as EMVP.
//!
//! ## Two variants — flat and IVF
//!
//! - [`FlatGpuState`] backs `BnTmScorer`. Degenerate single-cluster
//!   streaming wrapper; LRU has one entry but the NVML peak sampler
//!   runs uniformly across variants and the surface stays uniform
//!   with `IvfGpuState`.
//! - [`IvfGpuState`] backs `BnTmIvfScorer`. Per-cluster device
//!   buffers uploaded on miss via the same `ClusterStore`, evicted
//!   on budget pressure. Same streaming shape as emvp-IVF GPU.
//!
//! ## Launch-overhead caveat
//!
//! At SEC128 the kernel is small: m × 1024 field ops per cluster,
//! microseconds of compute on V100. The transfer stack (H2D `v_enc`,
//! kernel launch, D2H `r`) dominates per-query latency at our
//! typical cluster size (~316 vectors at 100k corpus / 317 centroids).
//! Future polish: pinned-memory transfers, kernel-fused multi-cluster
//! dispatch, GPU-side decode and verification.

use std::sync::Arc;

use cudarc::driver::{
    CudaContext, CudaFunction, CudaSlice, CudaStream, LaunchConfig, PushKernelArg,
};
use cudarc::nvrtc::Ptx;
use scorer_gpu_common::{
    ClusterStore, ClusterStoreError, DeviceCluster, PeakVramSampler, nvml_index_for_cuda_device,
    resolve_budget,
};

use crate::crypto::SparseMatrix;
use crate::params::BnTmParams;

/// Compiled PTX for the BN kernel. Generated by `build.rs` from
/// `src/gpu/kernels.cu`; the CUDA driver JIT-compiles it at first
/// launch. PTX targets compute_70 → forward-compatible across V100,
/// RTX 5000 Ada, and H100.
const BNTM_KERNEL_PTX: &str = include_str!(concat!(env!("OUT_DIR"), "/bntm_kernels.ptx"));

const KERNEL_COMPUTE_PRODUCTS: &str = "bntm_compute_products";
const KERNEL_DECODE_DENSE: &str = "bntm_decode_dense";
const KERNEL_ADD_MOD_VEC: &str = "bntm_add_mod_vec";

/// One thread per output row; 256 threads per block keeps register
/// pressure modest given the u128 accumulator.
const BLOCK_DIM: u32 = 256;

/// Block size for the elementwise `bntm_add_mod_vec` compose kernel.
/// One thread per output element; no reduction.
const ADD_MOD_BLOCK_DIM: u32 = 256;

#[derive(Debug, thiserror::Error)]
pub enum GpuError {
    #[error("CUDA driver error: {0}")]
    Driver(String),
    #[error("VRAM budget resolution failed: {0}")]
    Budget(String),
    #[error("NVML peak-VRAM sampler failed: {0}")]
    Sampler(String),
    #[error("cluster payload {requested_bytes} bytes exceeds budget {budget_bytes} bytes")]
    BudgetTooSmall {
        budget_bytes: u64,
        requested_bytes: u64,
    },
}

impl From<cudarc::driver::DriverError> for GpuError {
    fn from(e: cudarc::driver::DriverError) -> Self {
        GpuError::Driver(format!("{e:?}"))
    }
}

impl From<scorer_gpu_common::BudgetResolverError> for GpuError {
    fn from(e: scorer_gpu_common::BudgetResolverError) -> Self {
        GpuError::Budget(format!("{e}"))
    }
}

impl From<scorer_gpu_common::SamplerError> for GpuError {
    fn from(e: scorer_gpu_common::SamplerError) -> Self {
        GpuError::Sampler(format!("{e}"))
    }
}

impl From<ClusterStoreError<cudarc::driver::DriverError>> for GpuError {
    fn from(e: ClusterStoreError<cudarc::driver::DriverError>) -> Self {
        match e {
            ClusterStoreError::Upload(c) => GpuError::Driver(format!("{c:?}")),
            ClusterStoreError::BudgetTooSmall {
                budget_bytes,
                requested_bytes,
            } => GpuError::BudgetTooSmall {
                budget_bytes,
                requested_bytes,
            },
            ClusterStoreError::Sync(c) => GpuError::Driver(format!("{c:?}")),
        }
    }
}

/// Process-wide cached CUDA context + loaded BN kernel. Loaded once
/// per process the first time any GPU BN handle is built; shared by
/// every `FlatGpuState` / `IvfGpuState` so we don't re-compile PTX or
/// pay context-creation overhead per cluster. Mirrors the emvp-GPU
/// kernel cache; the two crates each have their own `OnceLock` since
/// they ship different PTX.
struct BnTmKernel {
    /// Drop order matters — keep the context alive for the
    /// OnceLock's `'static` lifetime so the stream / module / function
    /// handles below stay valid.
    #[allow(dead_code)]
    ctx: Arc<CudaContext>,
    stream: Arc<CudaStream>,
    /// Server-side `M_enc · v_enc` matvec at N = 1024.
    compute_products: CudaFunction,
    /// Dense matvec at the n_1 = 512 inner dimension. Launched twice
    /// per decode (for `AL · G` and `H · (L⊤ · v_enc)`).
    decode_dense: CudaFunction,
    /// Elementwise add over F_p, composes the two `decode_dense`
    /// outputs into a single length-`m` dense partial.
    add_mod_vec: CudaFunction,
}

fn kernel() -> Result<&'static BnTmKernel, GpuError> {
    use std::sync::OnceLock;
    static KERNEL: OnceLock<Result<BnTmKernel, String>> = OnceLock::new();

    let res = KERNEL.get_or_init(|| {
        let ctx = CudaContext::new(0).map_err(|e| format!("CudaContext::new: {e:?}"))?;
        let stream = ctx.default_stream();
        let module = ctx
            .load_module(Ptx::from_src(BNTM_KERNEL_PTX))
            .map_err(|e| format!("load_module: {e:?}"))?;
        let load = |name: &str| {
            module
                .load_function(name)
                .map_err(|e| format!("load_function {name}: {e:?}"))
        };
        let compute_products = load(KERNEL_COMPUTE_PRODUCTS)?;
        let decode_dense = load(KERNEL_DECODE_DENSE)?;
        let add_mod_vec = load(KERNEL_ADD_MOD_VEC)?;
        Ok(BnTmKernel {
            ctx,
            stream,
            compute_products,
            decode_dense,
            add_mod_vec,
        })
    });

    match res {
        Ok(k) => Ok(k),
        Err(e) => Err(GpuError::Driver(e.clone())),
    }
}

/// Device-resident per-cluster buffers + the row count they span.
/// Implements [`DeviceCluster`] so the streaming `ClusterStore` can
/// hold it and account its size against the VRAM budget. cudarc owns
/// the three `CudaSlice<u64>`s; `Drop` returns
/// the device memory to the cudarc memory pool — no manual free
/// needed.
///
/// `a_l_dev` and `h_dev` are row-major `m × n_1` and mirror the
/// `m_enc_dev` packing (flat `&[u64]` via `clone_htod`). All three
/// are read by `launch_compute_products` (M_enc) and
/// `launch_decode_dense_terms` (AL, H).
struct ClusterBuf {
    m_enc_dev: CudaSlice<u64>,
    a_l_dev: CudaSlice<u64>,
    h_dev: CudaSlice<u64>,
    m: usize,
}

// SAFETY: cudarc's `CudaSlice<u64>` isn't declared `Sync` upstream
// because the underlying device pointer is a raw FFI handle. The
// `ClusterStore` wraps each `ClusterBuf` in a `Mutex` and only
// reaches it through the `tokio::task::spawn_blocking` worker pool.
// Drop this `unsafe` if cudarc ever exposes `Send`/`Sync` directly
// on `CudaSlice`.
unsafe impl Send for ClusterBuf {}

impl DeviceCluster for ClusterBuf {
    fn device_bytes(&self) -> u64 {
        // M_enc (m·n·8) + AL (m·n_1·8) + H (m·n_1·8). The three
        // slices' `len()`s sum to the field-element count; multiply
        // by 8 for bytes. cudarc's internal scratch / kernel-arg
        // buffers aren't tracked here; the NVML peak sampler is the
        // source of truth for realised VRAM.
        ((self.m_enc_dev.len() + self.a_l_dev.len() + self.h_dev.len()) as u64) * 8
    }
}

/// Upload the three cluster buffers (M_enc + AL + H) to device via
/// the supplied stream. Used inside the `ClusterStore::get_or_upload`
/// closure; the stream is the store's dedicated upload stream so
/// these copies overlap compute on the sibling compute stream.
fn upload_cluster_buffers(
    stream: &Arc<CudaStream>,
    m_enc_host: &[u64],
    a_l_host: &[u64],
    h_host: &[u64],
    m: usize,
    params: BnTmParams,
) -> Result<ClusterBuf, cudarc::driver::DriverError> {
    debug_assert_eq!(m_enc_host.len(), m * params.n());
    debug_assert_eq!(a_l_host.len(), m * params.n1());
    debug_assert_eq!(h_host.len(), m * params.n1());
    let m_enc_dev = stream.clone_htod(m_enc_host)?;
    let a_l_dev = stream.clone_htod(a_l_host)?;
    let h_dev = stream.clone_htod(h_host)?;
    Ok(ClusterBuf {
        m_enc_dev,
        a_l_dev,
        h_dev,
        m,
    })
}

